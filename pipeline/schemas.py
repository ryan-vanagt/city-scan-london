_DDL_SILVER_METRICS = """
CREATE TABLE IF NOT EXISTS silver_metrics (
    borough_code     VARCHAR NOT NULL,
    borough_name     VARCHAR NOT NULL,
    timestamp        TIMESTAMPTZ NOT NULL,
    metric_name      VARCHAR NOT NULL,
    raw_value        DOUBLE,
    normalised_score DOUBLE NOT NULL CHECK (normalised_score >= 0 AND normalised_score <= 100),
    source           VARCHAR NOT NULL,
    ingested_at      TIMESTAMPTZ NOT NULL,
    pipeline_stage   VARCHAR DEFAULT 'silver'
);
"""

_DDL_GOLD_SCORES = """
CREATE TABLE IF NOT EXISTS gold_scores (
    borough_code       VARCHAR NOT NULL,
    borough_name       VARCHAR NOT NULL,
    timestamp          TIMESTAMPTZ NOT NULL,
    air_score          DOUBLE CHECK (air_score >= 0 AND air_score <= 100),
    transit_score      DOUBLE CHECK (transit_score >= 0 AND transit_score <= 100),
    sentiment_score    DOUBLE CHECK (sentiment_score >= 0 AND sentiment_score <= 100),
    immune_score       DOUBLE CHECK (immune_score >= 0 AND immune_score <= 100),
    green_space_score  DOUBLE CHECK (green_space_score >= 0 AND green_space_score <= 100),
    composite_score    DOUBLE NOT NULL CHECK (composite_score >= 0 AND composite_score <= 100),
    ingested_at        TIMESTAMPTZ NOT NULL,
    pipeline_stage     VARCHAR DEFAULT 'gold'
);
"""

_DDL_SILVER_DETAIL = """
CREATE TABLE IF NOT EXISTS silver_detail (
    borough_code VARCHAR NOT NULL,
    borough_name VARCHAR NOT NULL,
    timestamp    TIMESTAMPTZ NOT NULL,
    source       VARCHAR NOT NULL,
    category     VARCHAR NOT NULL,
    label        VARCHAR NOT NULL,
    value        DOUBLE,
    detail_text  VARCHAR,
    ingested_at  TIMESTAMPTZ NOT NULL
);
"""

_DDL_SILVER_HEADLINES = """
CREATE TABLE IF NOT EXISTS silver_headlines (
    timestamp       TIMESTAMPTZ NOT NULL,
    source          VARCHAR NOT NULL,
    title           VARCHAR NOT NULL,
    url             VARCHAR,
    sentiment_score DOUBLE,
    ingested_at     TIMESTAMPTZ NOT NULL
);
"""


def init_db(con: duckdb.DuckDBPyConnection) -> None:
    """Create all DuckDB tables if they do not already exist.

    Note: agent_logs and bulletin_logs are managed separately
    (agent_logs in data/agent_logs.duckdb via agents/logging_db.py).

    Args:
        con: An open DuckDB connection.
    """
    for ddl in (
        _DDL_SILVER_METRICS,
        _DDL_GOLD_SCORES,
        _DDL_SILVER_DETAIL,
        _DDL_SILVER_HEADLINES,
    ):
        con.execute(ddl)

    # Migration: add green_space_score column to existing gold_scores tables.
    # Note: DuckDB ALTER TABLE doesn't support CHECK constraints — the CHECK
    # is already in the CREATE TABLE DDL above, so new tables get it.
    try:
        con.execute(
            "ALTER TABLE gold_scores ADD COLUMN IF NOT EXISTS green_space_score DOUBLE"
        )
    except (duckdb.CatalogException, duckdb.ParserException) as e:
        logger.debug("Migration note (green_space_score): %s", e)

    logger.info("DuckDB tables initialised")
