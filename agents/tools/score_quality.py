"""
Tool: get_score_quality

Returns per-organ data-quality flags + 95% bootstrap CIs for a London borough.
Used by the Doctor Agent to decide whether a score is trustworthy enough for
fine-grained claims, or whether it deserves a "use with care" caveat in the
response (e.g. boroughs with sparse OpenAQ sensor coverage).

Data source:
    Generated by scripts/compute_score_quality.py from gold time-series.
    Output: data/static/score_quality.json.
"""

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

_DATA_PATH = Path(__file__).resolve().parent.parent.parent / "data" / "static" / "score_quality.json"

# Lazy-loaded cache
_quality_data: dict | None = None


def _load_data() -> dict:
    """Load and cache score-quality data from static JSON."""
    global _quality_data
    if _quality_data is None:
        if not _DATA_PATH.exists():
            logger.error(
                "Score quality data not found at %s — run scripts/compute_score_quality.py",
                _DATA_PATH,
            )
            return {}
        with open(_DATA_PATH, encoding="utf-8") as f:
            _quality_data = json.load(f)
    return _quality_data


def _resolve_borough(borough: str) -> tuple[str, dict] | None:
    """Resolve a borough name or ONS code to (code, borough_data).

    Accepts ONS codes (E09000012) or names (case-insensitive).
    Resolution: exact code → exact name → starts-with → contains.
    """
    if not borough or not borough.strip():
        return None

    data = _load_data()
    boroughs = data.get("boroughs", {})
    if not boroughs:
        return None

    query = borough.strip()

    if query in boroughs:
        return query, boroughs[query]

    query_lower = query.lower()

    for code, b in boroughs.items():
        if b.get("borough_name", "").lower() == query_lower:
            return code, b

    matches = [
        (code, b) for code, b in boroughs.items()
        if b.get("borough_name", "").lower().startswith(query_lower)
    ]
    if len(matches) == 1:
        return matches[0]

    matches = [
        (code, b) for code, b in boroughs.items()
        if query_lower in b.get("borough_name", "").lower()
    ]
    if len(matches) == 1:
        return matches[0]

    return None


def get_score_quality(borough: str) -> dict:
    """Get per-organ data-quality flags + 95% bootstrap CIs for a London borough.

    Each organ carries a reliability flag (green / amber / red) derived from
    bootstrap-of-mean CI on the borough's last 30 days of gold time-series,
    except for static-cadence signals (sentiment, modelled air, green-space
    variants) which carry an explicit disclosure note about cadence/scope.

    Use this BEFORE quoting any organ score with confidence — if the flag is
    amber or red for the organ in question, prepend a reliability caveat in
    the response (e.g. "based on a sparse sensor signal" / "London-wide proxy").

    Args:
        borough: Borough name (e.g. 'Hackney') or ONS code (e.g. 'E09000012').

    Returns:
        Dict with per-organ flags + CIs + disclosure notes, or error dict if
        borough not found.
    """
    borough = str(borough)[:100]
    resolved = _resolve_borough(borough)
    if resolved is None:
        return {"error": f"Borough not found: '{borough}'"}

    code, b = resolved
    metadata = _load_data().get("_metadata", {})

    return {
        "borough_name": b.get("borough_name"),
        "borough_code": code,
        "organs": b.get("organs", {}),
        "method_summary": metadata.get("method"),
    }
