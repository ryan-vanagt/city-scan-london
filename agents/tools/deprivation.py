"""
Tool: get_deprivation

Returns IMD 2025 (Index of Multiple Deprivation) data for a London borough,
including the overall rank and all 7 domain sub-scores. This is structural
context (long-term disadvantage), not a live signal.

Data source:
    MHCLG English Indices of Deprivation 2025 (File 10 — LAD summaries).
    Generated by scripts/fetch_imd.py → data/static/imd_borough.json.
"""

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

_DATA_PATH = Path(__file__).resolve().parent.parent.parent / "data" / "static" / "imd_borough.json"

# Lazy-loaded cache
_imd_data: dict | None = None


def _load_data() -> dict:
    """Load and cache IMD data from static JSON."""
    global _imd_data
    if _imd_data is None:
        if not _DATA_PATH.exists():
            logger.error("IMD data not found at %s — run scripts/fetch_imd.py", _DATA_PATH)
            return {}
        with open(_DATA_PATH, encoding="utf-8") as f:
            _imd_data = json.load(f)
    return _imd_data


def _resolve_borough(borough: str) -> tuple[str, dict] | None:
    """Resolve a borough name or ONS code to (code, borough_data).

    Accepts ONS codes (E09000012) or names (case-insensitive).
    Resolution: exact code → exact name → starts-with → contains.
    """
    if not borough or not borough.strip():
        return None

    data = _load_data()
    boroughs = data.get("boroughs", {})
    if not boroughs:
        return None

    query = borough.strip()

    # Exact code match
    if query in boroughs:
        return query, boroughs[query]

    # Name matching (case-insensitive)
    query_lower = query.lower()

    # Exact name
    for code, b in boroughs.items():
        if b["name"].lower() == query_lower:
            return code, b

    # Starts-with
    matches = [(code, b) for code, b in boroughs.items()
               if b["name"].lower().startswith(query_lower)]
    if len(matches) == 1:
        return matches[0]

    # Contains
    matches = [(code, b) for code, b in boroughs.items()
               if query_lower in b["name"].lower()]
    if len(matches) == 1:
        return matches[0]

    return None


def get_deprivation(borough: str) -> dict:
    """Get IMD 2025 deprivation data for a London borough.

    Returns the overall IMD rank (1-296, where 1 is most deprived nationally),
    score, percentage of LSOAs in the most deprived 10%, and all 7 domain
    sub-scores (income, employment, education, health, crime, barriers, living).

    Args:
        borough: Borough name (e.g. 'Hackney') or ONS code (e.g. 'E09000012').

    Returns:
        Dict with deprivation data, or error dict if borough not found.
    """
    resolved = _resolve_borough(borough)
    if resolved is None:
        return {"error": f"Borough not found: '{borough}'"}

    code, b = resolved
    rank = b["imd_rank"]

    return {
        "borough_name": b["name"],
        "borough_code": code,
        "imd_rank": rank,
        "imd_rank_description": f"{rank}{'st' if rank == 1 else 'nd' if rank == 2 else 'rd' if rank == 3 else 'th'} most deprived out of 296 local authorities in England",
        "imd_score": b["imd_score"],
        "pct_most_deprived_10": b["pct_most_deprived_10"],
        "domains": b.get("domains", {}),
    }
