"""
Tool: get_transit_access

Returns the TfL Public Transport Accessibility Level (PTAL) for a London
borough — the canonical access measure used by the GLA, TfL, and Cabinet
Office. Distinct from the live `transit_score` (tube line reliability):
PTAL captures structural network access, not real-time disruption.

Data source:
    TfL PTAL borough average (data.london.gov.uk).
    Generated by scripts/fetch_ptal.py → data/static/transit_access.json.

Vintage note: PTAL 2015 is the most recent published edition. PTAL is an
analytic dataset, not a live one — TfL only updates it on major network
changes. The 2015 edition predates the Elizabeth Line (2022); when asked
about boroughs the Elizabeth Line reaches (Newham, Tower Hamlets, parts
of Ealing/Hillingdon), the agent should disclose that 2015 PTAL
understates current access.
"""

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

_DATA_PATH = (
    Path(__file__).resolve().parent.parent.parent / "data" / "static" / "transit_access.json"
)

_ptal_data: dict | None = None


def _load_data() -> dict:
    global _ptal_data
    if _ptal_data is None:
        if not _DATA_PATH.exists():
            logger.error(
                "PTAL data not found at %s — run scripts/fetch_ptal.py",
                _DATA_PATH,
            )
            return {}
        with open(_DATA_PATH, encoding="utf-8") as f:
            _ptal_data = json.load(f)
    return _ptal_data


def _resolve_borough(borough: str) -> tuple[str, dict] | None:
    if not borough or not borough.strip():
        return None
    data = _load_data()
    boroughs = data.get("boroughs", {})
    if not boroughs:
        return None
    query = borough.strip()
    if query in boroughs:
        return query, boroughs[query]
    query_lower = query.lower()
    for code, b in boroughs.items():
        if b.get("name", "").lower() == query_lower:
            return code, b
    matches = [
        (code, b) for code, b in boroughs.items()
        if b.get("name", "").lower().startswith(query_lower)
    ]
    if len(matches) == 1:
        return matches[0]
    matches = [
        (code, b) for code, b in boroughs.items()
        if query_lower in b.get("name", "").lower()
    ]
    if len(matches) == 1:
        return matches[0]
    return None


def get_transit_access(borough: str) -> dict:
    """Get the TfL PTAL transit-access score for a London borough.

    Returns the official PTAL band (1a → 6b), the raw AvPTAI 2015 figure,
    and a 0–100 normalised score derived by log-transforming AvPTAI and
    min-max scaling across the 33 boroughs (compresses the City of London
    outlier so the gradient is readable).

    PTAL is the SDG 11.2-aligned access measure, distinct from live
    `transit_score` (tube line reliability/disruption). Use this when the
    user asks about transport access, equity, or 'who can reach transit',
    rather than 'are the trains running'.

    Args:
        borough: Borough name (e.g. 'Hackney') or ONS code (e.g. 'E09000012').

    Returns:
        Dict with PTAL data + vintage disclosure, or error dict if borough
        not found.
    """
    borough = str(borough)[:100]
    resolved = _resolve_borough(borough)
    if resolved is None:
        return {"error": f"Borough not found: '{borough}'"}
    code, b = resolved
    metadata = _load_data().get("_metadata", {})
    return {
        "borough_name": b.get("name"),
        "borough_code": code,
        "ptal_band": b.get("ptal_band"),
        "avptai_2015": b.get("avptai_2015"),
        "score_0_to_100": b.get("score_0_to_100"),
        "vintage": metadata.get("vintage"),
        "definition": metadata.get("definition"),
        "sdg_relevance": metadata.get("sdg_relevance"),
    }
